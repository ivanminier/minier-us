#!/usr/bin/env node
// Whole-building capacity test fits for Trinity Peaks and Trinity Rise.
// Inputs: the generated plan schedules (src/data/plans-index.json), the Trinity facts snapshot,
// and studies/model/testfit-inputs.json. Output: src/data/testfit.json (read by the site).
// This is arithmetic on exploratory assumptions. It is not a site test fit: no parcel survey,
// existing-building inventory, setbacks, or zoning analysis has been done.

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const J = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
const plans = Object.fromEntries(J("src/data/plans-index.json").map((p) => [p.id, p]));
const facts = J("src/data/trinity-facts.json").facts;
const I = J("studies/model/testfit-inputs.json");

const floor = plans["peaks-floor-a"];
const r4a = plans["rise-r4a"];
const round = (v, d = 0) => Math.round(v * 10 ** d) / 10 ** d;

// Height arithmetic.
const height = (resFloors, ftf) => I.height.groundFtf + resFloors * ftf + I.height.roofAllowance;
const maxResFloorsUnder = (limit, ftf) => Math.floor((limit - I.height.groundFtf - I.height.roofAllowance) / ftf);

// ---------- Trinity Peaks
const bedsPerFloor = floor.beds;
const floorGsf = floor.grossArea;
const peaksScenarios = I.peaks.residentialFloors.map(({ label, floors }) => {
  const bedsPerBar = bedsPerFloor * floors;
  const out = { label, residentialFloors: floors, bedsPerBar };
  for (const [k, beds] of [["low", facts.peaks_beds.low], ["high", facts.peaks_beds.high]]) {
    const bars = beds / bedsPerBar;
    const footprint = bars * floorGsf;
    const gsf = bars * floorGsf * (floors + 1); // ground floor = one full floor plate, no beds
    out[k] = { beds, barsEquivalent: round(bars, 1), footprintSf: round(footprint, -2), gsf: round(gsf, -3), gsfPerBed: round(gsf / beds) };
  }
  out.heightFt = { at10: height(floors, 10), at105: height(floors, 10.5), at11: height(floors, 11) };
  out.over55 = out.heightFt.at105 > 55;
  return out;
});

// ---------- Trinity Rise (4-bedroom apartments on a double-loaded floor)
const unitW = r4a.width, unitD = r4a.depth;
const riseFloor = (unitsPerFloor) => {
  const perSide = Math.ceil(unitsPerFloor / 2);
  const length = perSide * unitW + I.rise.coreLength;
  const depth = unitD * 2 + I.rise.corridor;
  return { unitsPerFloor, bedsPerFloor: unitsPerFloor * r4a.beds, plateLength: length, plateDepth: depth, plateGsf: length * depth, netUnitSf: unitsPerFloor * r4a.grossArea };
};
const riseScenarios = [];
for (const u of I.rise.unitsPerFloor) {
  const f = riseFloor(u);
  for (const stories of I.rise.stories) {
    const res = stories - 1; // ground floor: lobby, Northline Cafe, amenities, no beds
    const beds = f.bedsPerFloor * res;
    riseScenarios.push({ ...f, stories, residentialFloors: res, beds, gsf: round(f.plateGsf * stories, -3), gsfPerBed: round((f.plateGsf * stories) / beds), efficiency: round(f.netUnitSf / f.plateGsf, 2), inBaseline: beds >= facts.rise_beds.low && beds <= facts.rise_beds.high, heightFt: height(res, I.height.riseFtf) });
  }
}
const storiesFor = (beds, u) => 1 + Math.ceil(beds / riseFloor(u).bedsPerFloor);

const result = {
  _about: "Generated by studies/model/testfit.mjs. Arithmetic on exploratory assumptions; not a site test fit.",
  generated: I.date,
  basis: {
    peaksFloor: { plan: floor.id, version: floor.version, bedsPerFloor, floorGsf, gsfPerBedFloor: floor.grossAreaPerBed, width: floor.width, depth: floor.depth },
    riseUnit: { plan: r4a.id, version: r4a.version, beds: r4a.beds, unitSf: r4a.grossArea, width: unitW, depth: unitD },
    trinityRelease: J("src/data/trinity-facts.json").release,
    targets: { peaks: facts.peaks_beds.value, rise: facts.rise_beds.value, riseHeight: facts.rise_height.value },
    site: I.site,
    height: I.height,
  },
  peaks: peaksScenarios,
  peaksUnder55: Object.fromEntries([10, 10.5, 11].map((ftf) => [ftf, maxResFloorsUnder(55, ftf)])),
  rise: riseScenarios,
  riseStoriesNeeded: Object.fromEntries(I.rise.unitsPerFloor.map((u) => [u, { beds300: storiesFor(facts.rise_beds.low, u), beds400: storiesFor(facts.rise_beds.high, u) }])),
  coverage: (() => {
    const siteSf = I.site.acres * 43560;
    const allowed = siteSf * I.site.coverage;
    const mid = peaksScenarios.find((s) => s.residentialFloors === 5);
    const riseMid = riseScenarios.find((s) => s.unitsPerFloor === 8 && s.stories === 10);
    const used = mid.high.footprintSf + riseMid.plateLength * riseMid.plateDepth;
    return { siteSf: round(siteSf, -3), coverageRate: I.site.coverage, allowedFootprintSf: round(allowed, -3), peaksFootprintAt5Floors: mid.high.footprintSf, riseFootprint8Units: round(riseMid.plateLength * riseMid.plateDepth, -2), share: round(used / allowed, 2), excludes: "Existing buildings that stay (Cottages, academic buildings), the proposed parking garage, Northside Dining beyond the Peaks footprint, and Trinity Way are not counted." };
  })(),
};
writeFileSync(join(ROOT, "src", "data", "testfit.json"), JSON.stringify(result, null, 2) + "\n");

console.log(`Peaks floor: ${bedsPerFloor} beds / ${floorGsf} sf`);
for (const s of peaksScenarios) console.log(`  ${s.label}: ${s.low.barsEquivalent}-${s.high.barsEquivalent} bar-equivalents, ${s.low.footprintSf}-${s.high.footprintSf} sf footprint, height ${s.heightFt.at10}-${s.heightFt.at11} ft`);
console.log(`  residential floors that fit under 55 ft:`, result.peaksUnder55);
for (const s of riseScenarios) console.log(`  Rise ${s.unitsPerFloor} units/floor x ${s.stories} stories: ${s.beds} beds ${s.inBaseline ? "(in 300-400)" : ""}, ${s.gsfPerBed} gsf/bed, ~${s.heightFt} ft`);
console.log(`  coverage share (Peaks 5 floors high case + Rise 8 units):`, result.coverage.share);
