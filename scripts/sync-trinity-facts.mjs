#!/usr/bin/env node
// Keeps minier.us's Trinity figures tied to the authoritative Trinity Redistricting data.
//
// The canonical source is `data/facts.json` in the ivanminier/trinity-site repository
// (the file that builds trinityredistricting.com). This script copies a fixed list of
// facts from it into `src/data/trinity-facts.json`, which the portfolio reads at build
// time. There is no runtime dependency on the other site.
//
//   node scripts/sync-trinity-facts.mjs                 write the snapshot from ../trinity-site
//   node scripts/sync-trinity-facts.mjs --check         fail if the snapshot is out of date
//   node scripts/sync-trinity-facts.mjs --from <path>   use another checkout or a downloaded copy
//
// The snapshot records the Trinity commit and the SHA-256 of the facts file it was copied
// from (`pinned`). When no local Trinity checkout is available (for example in Cloudflare
// Pages builds), --check downloads data/facts.json at that pinned commit from GitHub and
// verifies both the hash and the copied facts. Only if GitHub cannot be reached does it fall
// back to validating the snapshot's own structure, with a notice.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const fromIdx = args.indexOf("--from");
const fromPath = resolve(
  fromIdx >= 0 ? args[fromIdx + 1] : join(ROOT, "..", "trinity-site", "data", "facts.json"),
);
const SNAPSHOT = join(ROOT, "src", "data", "trinity-facts.json");

/** Facts the portfolio is allowed to quote. Add an id here before using a new figure. */
const IDS = [
  "peaks_beds",
  "peaks_height",
  "rise_beds",
  "rise_height",
  "rise_tall",
  "new_beds",
  "replacement_beds",
  "net_new_beds",
  "peaks_net_new",
  "ra_rooms",
  "staff_apartments",
  "capital_range",
  "capital_components",
  "per_new_bed",
  "per_net_new_bed",
  "rise_per_bed",
  "zoning_current",
  "pc_2022",
  "mou_2023",
  "mou_status",
  "catamount_woods",
  "bench_vt",
  "bench_unc",
  "trinity_halls",
  "upperclass_options",
  "catamount_east",
  "vacancy",
];

const REPO = "ivanminier/trinity-site";
const sha256 = (s) => createHash("sha256").update(s).digest("hex");

function build(canonical, pinned) {
  const byId = Object.fromEntries(canonical.facts.map((f) => [f.id, f]));
  const missing = IDS.filter((id) => !byId[id]);
  if (missing.length) throw new Error(`canonical facts.json lacks: ${missing.join(", ")}`);
  const keep = ["id", "label", "value", "low", "high", "units", "meaning", "status", "formula"];
  return {
    _about:
      "Generated by scripts/sync-trinity-facts.mjs from ivanminier/trinity-site data/facts.json. Do not edit by hand; edit the canonical file and re-sync.",
    source: "https://trinityredistricting.com/proposal.html",
    pinned,
    release: {
      version: canonical.release.version,
      date: canonical.release.date,
      dateLabel: canonical.release.dateLabel,
      ...(canonical.release.revised ? { revised: canonical.release.revised, revisedLabel: canonical.release.revisedLabel } : {}),
    },
    facts: Object.fromEntries(
      IDS.map((id) => [
        id,
        Object.fromEntries(keep.filter((k) => byId[id][k] !== undefined).map((k) => [k, byId[id][k]])),
      ]),
    ),
  };
}

function validateShape(snap) {
  const problems = [];
  if (!snap.release?.version || !snap.release?.date) problems.push("release version/date missing");
  if (!/^[0-9a-f]{40}$/.test(snap.pinned?.commit || "")) problems.push("pinned Trinity commit missing");
  if (!/^[0-9a-f]{64}$/.test(snap.pinned?.factsSha256 || "")) problems.push("pinned facts hash missing");
  for (const id of IDS) if (!snap.facts?.[id]?.value) problems.push(`fact ${id} missing`);
  // Arithmetic the portfolio relies on: new beds = Peaks + Rise; net-new = new - replaced.
  const f = snap.facts;
  if (f.peaks_beds && f.rise_beds && f.new_beds) {
    if (f.peaks_beds.low + f.rise_beds.low !== f.new_beds.low) problems.push("new_beds.low != peaks.low + rise.low");
    if (f.peaks_beds.high + f.rise_beds.high !== f.new_beds.high) problems.push("new_beds.high != peaks.high + rise.high");
  }
  return problems;
}

const current = existsSync(SNAPSHOT) ? JSON.parse(readFileSync(SNAPSHOT, "utf8")) : null;
const fmt = (o) => JSON.stringify(o, null, 2) + "\n";
const fail = (msg) => { console.error(msg); process.exit(1); };

// Compare everything except the pinned commit, which only identifies where the copy came from.
const sameFacts = (a, b) => a && b && fmt({ ...a, pinned: { factsSha256: a.pinned?.factsSha256 } }) === fmt({ ...b, pinned: { factsSha256: b.pinned?.factsSha256 } });

if (!existsSync(fromPath)) {
  if (!CHECK) fail(`Canonical facts not found at ${fromPath}. Pass --from <path to trinity-site/data/facts.json>.`);
  const problems = current ? validateShape(current) : ["snapshot missing"];
  if (problems.length) fail("Trinity facts snapshot invalid:\n - " + problems.join("\n - "));
  const { commit, factsSha256 } = current.pinned;
  let raw = null;
  try {
    const res = await fetch(`https://raw.githubusercontent.com/${REPO}/${commit}/data/facts.json`, { signal: AbortSignal.timeout(15000) });
    if (res.ok) raw = await res.text();
  } catch {}
  if (raw === null) {
    console.log(`notice: no trinity-site checkout and GitHub unreachable; snapshot structure OK (pinned ${commit.slice(0, 7)}, release ${current.release.version}). Pinned comparison skipped.`);
    process.exit(0);
  }
  if (sha256(raw) !== factsSha256) fail(`Pinned Trinity facts at ${commit.slice(0, 7)} do not match the recorded hash.`);
  const rebuilt = build(JSON.parse(raw), current.pinned);
  if (fmt(rebuilt) !== fmt(current)) fail(`Trinity facts snapshot differs from data/facts.json at pinned commit ${commit.slice(0, 7)}. Run: npm run sync:trinity`);
  console.log(`ok   Trinity facts snapshot matches pinned trinity-site ${commit.slice(0, 7)} (release ${current.release.version}).`);
  process.exit(0);
}

const raw = readFileSync(fromPath, "utf8");
let commit = null;
try { commit = execFileSync("git", ["-C", dirname(fromPath), "rev-parse", "HEAD"], { encoding: "utf8" }).trim(); } catch {}
if (!commit && current?.pinned?.factsSha256 === sha256(raw)) commit = current.pinned.commit;
if (!commit) fail(`Cannot determine the trinity-site commit for ${fromPath}.`);
const next = build(JSON.parse(raw), { repo: REPO, commit, factsSha256: sha256(raw) });
const problems = validateShape(next);
if (problems.length) fail("Canonical data failed portfolio checks:\n - " + problems.join("\n - "));

if (CHECK) {
  if (!sameFacts(current, next)) fail(`Trinity facts snapshot is out of date with ${fromPath} (canonical release ${next.release.version}, ${next.release.date}). Run: npm run sync:trinity`);
  console.log(`ok   Trinity facts snapshot matches canonical release ${next.release.version} (${next.release.date}); pinned ${current.pinned.commit.slice(0, 7)}.`);
} else {
  const text = fmt(next);
  const same = current && fmt(current) === text;
  if (!same) writeFileSync(SNAPSHOT, text);
  console.log(`${same ? "unchanged" : "wrote"} src/data/trinity-facts.json (release ${next.release.version}, pinned ${commit.slice(0, 7)})`);
}
